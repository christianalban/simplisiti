<?php

namespace Alban\Simplisiti\Mcp\Tools;

use Alban\Simplisiti\Http\Resources\ResourceResource;
use Alban\Simplisiti\Models\Resource;
use Illuminate\Contracts\JsonSchema\JsonSchema;
use Laravel\Mcp\Request;
use Laravel\Mcp\Response;
use Laravel\Mcp\Server\Tool;
use Laravel\Mcp\Server\Tools\Annotations\IsReadOnly;

#[IsReadOnly]
class AvailableResourcesTool extends Tool
{
    protected string $description = <<<'MARKDOWN'
Lists static resources available in Simplisiti with a compact default response.

A resource is a file served by Simplisiti, such as an image, video, document, archive, spreadsheet, presentation, or other MIME type accepted by the resource requests. Resources can be selected by component variables of type `resource` and their generated URL can be used in page content.

When `query` is omitted or blank, the tool returns only each resource's `id` and `name` to minimize response size. Use the identifier with `UpdateResourceTool` or `DeleteResourceTool`.

When `query` is provided, the tool performs a case-insensitive partial search by resource name and returns every matching resource expanded with its `id`, `name`, stored `path`, and public `url`. Use a focused query when the agent needs the URL or needs to identify a resource for an update or deletion.

This tool is read-only. It does not inspect file contents, search inside documents, download files, or modify resources. Use `ResourceDocsTool` for the resource model and the specialized create/update/delete documentation tools for operation-specific rules.

### Response structure

Without `query`, the response is an array of:
- **id** (integer): Resource identifier.
- **name** (string): Resource name, or the original downloaded filename when no custom name was supplied.

With `query`, the response is an array of complete resource objects:
- **id** (integer): Resource identifier.
- **name** (string): Resource name.
- **path** (string): Path stored on the configured resources disk.
- **url** (string): Public URL generated by Simplisiti.

An empty query uses compact mode and a query with no matches returns an empty array.
MARKDOWN;

    public function handle(Request $request): Response
    {
        $validated = $request->validate([
            'query' => 'nullable|string',
        ]);
        $query = trim($validated['query'] ?? '');

        if ($query === '') {
            $resources = Resource::query()
                ->select(['id', 'name'])
                ->orderBy('name')
                ->get()
                ->map(fn (Resource $resource): array => [
                    'id' => $resource->id,
                    'name' => $resource->name,
                ])
                ->all();

            return Response::json($resources);
        }

        $normalizedQuery = function_exists('mb_strtolower')
            ? mb_strtolower($query, 'UTF-8')
            : strtolower($query);
        $resources = Resource::query()
            ->whereRaw('LOWER(name) LIKE ?', ["%{$normalizedQuery}%"])
            ->orderBy('name')
            ->get();

        return Response::json(ResourceResource::collection($resources)->resolve());
    }

    /**
     * @return array<string, \Illuminate\Contracts\JsonSchema\JsonSchema>
     */
    public function schema(JsonSchema $schema): array
    {
        return [
            'query' => $schema->string()
                ->description('Optional case-insensitive partial search by resource name. Omit it for compact id/name results; provide it to expand matching resources.')
                ->nullable(),
        ];
    }
}
